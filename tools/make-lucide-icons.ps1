# Rasterise les icones Lucide (ISC) en masques alpha embarques.
#
# Pourquoi des masques et pas des PNG : embarquer du PNG obligerait a decoder une image
# a l'execution, donc WIC en P/Invoke ou une dependance graphique. Un tableau de
# couvertures alpha se consomme directement par la chaine de rendu premultipliee et ne
# coute aucun decodeur. ~11 Ko pour 5 icones en 4 tailles.
#
# Prerequis : Chrome installe, et les .svg presents dans tools/lucide/.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$root   = Split-Path -Parent $PSScriptRoot
$dir    = Join-Path $PSScriptRoot 'lucide'
$chrome = 'C:\Program Files\Google\Chrome\Application\chrome.exe'

# Nom du fichier SVG -> nom de l'icone dans le code. L'ordre fixe les valeurs de l'enum.
$icons = [ordered]@{
  'eye-off'      = 'HideIcons'
  'panel-bottom' = 'Taskbar'
  'keyboard'     = 'Keyboard'
  'zap'          = 'Autostart'
  'x'            = 'Quit'
}

# Le trait est epaissi aux petites tailles : Lucide est dessine pour 24 px, et un
# stroke-width de 2 devient anemique une fois reduit a 16.
$sizes = @(@{px = 16; sw = 2.25}, @{px = 20; sw = 2.1}, @{px = 24; sw = 2.0}, @{px = 32; sw = 2.0})
$cell  = 32

# --- planche HTML : une ligne par icone, une colonne par taille ------------------
$parts = New-Object System.Collections.Generic.List[string]
$r = 0
foreach ($svgName in $icons.Keys) {
  $svg = Get-Content (Join-Path $dir "$svgName.svg") -Raw
  if ($svg -notmatch '(?s)<svg\b.*?>(.*)</svg>') { throw "SVG illisible : $svgName" }
  $inner = $Matches[1].Trim()
  $c = 0
  foreach ($s in $sizes) {
    $x = $c * $cell
    $y = $r * $cell
    $parts.Add("<svg style=""position:absolute;left:${x}px;top:${y}px"" width=""$($s.px)"" height=""$($s.px)"" viewBox=""0 0 24 24"" fill=""none"" stroke=""#ffffff"" stroke-width=""$($s.sw)"" stroke-linecap=""round"" stroke-linejoin=""round"">$inner</svg>")
    $c++
  }
  $r++
}

$w = $cell * $sizes.Count
$h = $cell * $icons.Count
$html = "<!doctype html><html><head><meta charset=""utf-8""><style>html,body{margin:0;padding:0;background:transparent}body{width:${w}px;height:${h}px;position:relative}</style></head><body>" + ($parts -join '') + "</body></html>"
$htmlPath = Join-Path $dir 'sheet.html'
[System.IO.File]::WriteAllText($htmlPath, $html, [System.Text.UTF8Encoding]::new($false))

$png = Join-Path $dir 'sheet.png'
if (Test-Path $png) { Remove-Item $png }
& $chrome --headless=new --disable-gpu --hide-scrollbars --default-background-color=00000000 --force-device-scale-factor=1 --window-size=$w,$h --screenshot=$png "file:///$($htmlPath -replace '\\','/')" | Out-Null
if (-not (Test-Path $png)) { throw "Chrome n'a pas produit la planche" }

# --- extraction des canaux alpha ------------------------------------------------
$bmp = New-Object System.Drawing.Bitmap($png)
$encoded = New-Object System.Collections.Generic.List[string]
$names = @($icons.Values)
for ($ri = 0; $ri -lt $names.Count; $ri++) {
  for ($ci = 0; $ci -lt $sizes.Count; $ci++) {
    $px = $sizes[$ci].px
    $buf = New-Object byte[] ($px * $px)
    for ($y = 0; $y -lt $px; $y++) {
      for ($x = 0; $x -lt $px; $x++) {
        $buf[$y * $px + $x] = $bmp.GetPixel($ci * $cell + $x, $ri * $cell + $y).A
      }
    }
    $encoded.Add([Convert]::ToBase64String($buf))
  }
}
$bmp.Dispose()

# --- generation du source C# ----------------------------------------------------
$nl = "`r`n"
$out = New-Object System.Text.StringBuilder
[void]$out.Append('// <auto-generated>' + $nl)
[void]$out.Append('//     Genere par tools/make-lucide-icons.ps1. Ne pas editer a la main.' + $nl)
[void]$out.Append('//     Icones Lucide (https://lucide.dev), licence ISC.' + $nl)
[void]$out.Append('// </auto-generated>' + $nl + $nl)
# Roslyn traite tout fichier *.g.cs comme du code genere et exige sa propre directive
# nullable (CS8669). L'emettre ici evite d'avoir a desactiver l'avertissement pour tout
# le projet, ce qui masquerait de vrais problemes ailleurs.
[void]$out.Append('#nullable enable' + $nl + $nl)
[void]$out.Append('namespace DesktopIconsToggle;' + $nl + $nl)
[void]$out.Append('/// <summary>' + $nl)
[void]$out.Append('/// Masques alpha des icones du menu, rasterises depuis Lucide. Stockes comme couvertures' + $nl)
[void]$out.Append('/// alpha plutot que comme PNG : l''application n''a donc besoin ni de decodeur d''image ni' + $nl)
[void]$out.Append('/// de police d''icones a l''execution, et le masque alimente directement le rendu' + $nl)
[void]$out.Append('/// premultiplie deja en place.' + $nl)
[void]$out.Append('/// </summary>' + $nl)
[void]$out.Append('internal static class LucideIcons' + $nl)
[void]$out.Append('{' + $nl)
[void]$out.Append('    public enum Icon' + $nl)
[void]$out.Append('    {' + $nl)
for ($i = 0; $i -lt $names.Count; $i++) {
  [void]$out.Append("        $($names[$i]) = $i," + $nl)
}
[void]$out.Append('    }' + $nl + $nl)
[void]$out.Append('    /// <summary>Tailles disponibles, en pixels, par ordre croissant.</summary>' + $nl)
[void]$out.Append('    public static readonly int[] Sizes = [' + (($sizes | ForEach-Object { $_.px }) -join ', ') + '];' + $nl + $nl)
[void]$out.Append('    // Ordre : icone majeure, taille mineure.' + $nl)
[void]$out.Append('    private static readonly string[] Encoded =' + $nl)
[void]$out.Append('    [' + $nl)
$k = 0
for ($ri = 0; $ri -lt $names.Count; $ri++) {
  for ($ci = 0; $ci -lt $sizes.Count; $ci++) {
    [void]$out.Append("        // $($names[$ri]) $($sizes[$ci].px)px" + $nl)
    [void]$out.Append('        "' + $encoded[$k] + '",' + $nl)
    $k++
  }
}
[void]$out.Append('    ];' + $nl + $nl)
[void]$out.Append('    private static readonly byte[]?[] Cache = new byte[]?[Encoded.Length];' + $nl + $nl)
[void]$out.Append('    /// <summary>La taille disponible la plus proche de celle demandee.</summary>' + $nl)
[void]$out.Append('    public static int NearestSize(int requested)' + $nl)
[void]$out.Append('    {' + $nl)
[void]$out.Append('        int best = Sizes[0];' + $nl)
[void]$out.Append('        int bestGap = System.Math.Abs(requested - best);' + $nl + $nl)
[void]$out.Append('        foreach (int size in Sizes)' + $nl)
[void]$out.Append('        {' + $nl)
[void]$out.Append('            int gap = System.Math.Abs(requested - size);' + $nl)
[void]$out.Append('            if (gap < bestGap)' + $nl)
[void]$out.Append('            {' + $nl)
[void]$out.Append('                best = size;' + $nl)
[void]$out.Append('                bestGap = gap;' + $nl)
[void]$out.Append('            }' + $nl)
[void]$out.Append('        }' + $nl + $nl)
[void]$out.Append('        return best;' + $nl)
[void]$out.Append('    }' + $nl + $nl)
[void]$out.Append('    /// <summary>Couvertures alpha, une par pixel, balayees ligne par ligne.</summary>' + $nl)
[void]$out.Append('    public static byte[] Mask(Icon icon, int size)' + $nl)
[void]$out.Append('    {' + $nl)
[void]$out.Append('        int sizeIndex = System.Array.IndexOf(Sizes, size);' + $nl)
[void]$out.Append('        if (sizeIndex < 0)' + $nl)
[void]$out.Append('        {' + $nl)
[void]$out.Append('            throw new System.ArgumentOutOfRangeException(nameof(size));' + $nl)
[void]$out.Append('        }' + $nl + $nl)
[void]$out.Append('        int index = ((int)icon * Sizes.Length) + sizeIndex;' + $nl)
[void]$out.Append('        return Cache[index] ??= System.Convert.FromBase64String(Encoded[index]);' + $nl)
[void]$out.Append('    }' + $nl)
[void]$out.Append('}' + $nl)

$outPath = Join-Path $root 'src\DesktopIconsToggle\LucideIcons.g.cs'
[System.IO.File]::WriteAllText($outPath, $out.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output "genere : $outPath ($([math]::Round((Get-Item $outPath).Length / 1KB, 1)) Ko)"
